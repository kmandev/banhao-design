  end if;

  return new;
end;
$$;

create trigger payment_events_enforce_immutable_columns
  before update or delete on public.payment_events
  for each row execute function public.payment_events_enforce_immutable_columns();

revoke all on public.payment_events from anon, authenticated;
alter table public.payment_events enable row level security;

-- ---------------------------------------------------------------------------
-- payment_transactions — actual money movements the provider reports
-- ---------------------------------------------------------------------------
--
-- This is where a SURPLUS payment (a second successful transaction against
-- an already-SUCCESS payment) is recorded, so real cash never silently
-- vanishes from the books — see the ledger-domain migration for how its
-- entry-group key differs from the webhook's dedup key.

create table public.payment_transactions (
  id uuid primary key default gen_random_uuid(),
  payment_id uuid not null references public.payments (id) on delete restrict,
  payment_attempt_id uuid references public.payment_attempts (id) on delete set null,
  direction text not null check (direction in ('IN', 'OUT')),
  amount_satang bigint not null check (amount_satang > 0),
  provider_transaction_id text not null,
  occurred_at timestamptz not null default now(),

  constraint payment_transactions_provider_txn_key unique (provider_transaction_id)
);

comment on table public.payment_transactions is
  'An actual money movement the provider reported. Immutable and append-only — a duplicate payment (as opposed to a duplicate webhook event) is recorded here rather than swallowed.';

create index payment_transactions_payment_idx on public.payment_transactions (payment_id);

create trigger payment_transactions_reject_mutation
  before update or delete on public.payment_transactions
  for each row execute function public.reject_mutation();

revoke all on public.payment_transactions from anon, authenticated;
alter table public.payment_transactions enable row level security;

-- ---------------------------------------------------------------------------
-- refunds — a payment-domain state, never an order state (DEC-027)
-- ---------------------------------------------------------------------------

create table public.refunds (
  id uuid primary key default gen_random_uuid(),
  payment_id uuid not null references public.payments (id) on delete restrict,
  refund_reference text not null,
  state text not null default 'REFUND_REQUESTED' check (state in (
    'REFUND_REQUESTED', 'REFUND_PENDING', 'REFUND_PROCESSING',
    'REFUNDED', 'REFUND_REJECTED', 'REFUND_FAILED'
  )),
  amount_satang bigint not null check (amount_satang > 0),
  reason text not null,
  requested_by uuid references public.profiles (id) on delete set null,
  approved_by uuid references public.profiles (id) on delete set null,
  -- Not explicitly listed among docs/DATABASE_DESIGN.md § 9's refunds
  -- columns, but required by its own stated unique constraint
  -- "(provider, provider_refund_id)". Added to make that constraint
  -- implementable — see docs/DATABASE_MIGRATION_V1_REPORT.md.
  provider text,
  provider_refund_id text,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint refunds_reference_key unique (refund_reference)
);

comment on table public.refunds is
  'DEC-027: refund lives in the payment domain. Order = CANCELLED and Payment/Refund = REFUNDED can and do coexist — no order column ever holds a refund status. amount_satang, payment_id and refund_reference are immutable after creation. Never deleted.';

create unique index refunds_provider_refund_idx
